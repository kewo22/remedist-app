import { GetObjectCommand, NoSuchKey, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { Logger } from '@nestjs/common';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve, sep } from 'node:path';
import type { AppConfig } from '../../config/app-config';

export interface StoredFile {
  body: Buffer;
  contentType: string;
}

/** Thrown by `get` when there is no object under that key. */
export class StoredFileNotFoundError extends Error {
  constructor(key: string) {
    super(`No stored file under ${key}`);
    this.name = 'StoredFileNotFoundError';
  }
}

/**
 * Private file storage (intake photos, later scans and reports). Files are written and read only
 * through the API, which checks access and logs clinical reads; nothing is publicly readable.
 * Keys are generated by the API, never taken from a request.
 */
export abstract class FileStorage {
  abstract readonly isDemo: boolean;
  abstract put(key: string, body: Buffer, contentType: string): Promise<void>;
  /** Throws StoredFileNotFoundError when the key doesn't exist. */
  abstract get(key: string): Promise<StoredFile>;
}

const CONNECTION_TIMEOUT_MS = 5_000;
const REQUEST_TIMEOUT_MS = 30_000;

/** Neon Object Storage, through its S3-compatible API (path-style addressing only). */
export class S3FileStorage extends FileStorage {
  readonly isDemo = false;
  private readonly client: S3Client;

  constructor(
    private readonly bucket: string,
    options: { endpoint: string; region: string; accessKeyId: string; secretAccessKey: string },
  ) {
    super();
    this.client = new S3Client({
      endpoint: options.endpoint,
      region: options.region,
      credentials: { accessKeyId: options.accessKeyId, secretAccessKey: options.secretAccessKey },
      forcePathStyle: true,
      requestHandler: { connectionTimeout: CONNECTION_TIMEOUT_MS, requestTimeout: REQUEST_TIMEOUT_MS },
    });
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    await this.client.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: body, ContentType: contentType }));
  }

  async get(key: string): Promise<StoredFile> {
    try {
      const result = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
      if (!result.Body) {
        throw new StoredFileNotFoundError(key);
      }
      return {
        body: Buffer.from(await result.Body.transformToByteArray()),
        contentType: result.ContentType ?? 'application/octet-stream',
      };
    } catch (error) {
      if (error instanceof NoSuchKey) {
        throw new StoredFileNotFoundError(key);
      }
      throw error;
    }
  }
}

/**
 * No storage settings: files go to a folder in the OS temp directory, so uploads can be tried
 * locally. Refused in production, where that disk is temporary and the files would be lost.
 */
export class DemoFileStorage extends FileStorage {
  readonly isDemo = true;
  private readonly root = resolve(tmpdir(), 'remedist-demo-storage');

  constructor(private readonly isProduction: boolean) {
    super();
  }

  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    if (this.isProduction) {
      throw new Error('Object storage is not configured');
    }
    const path = this.pathFor(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, body);
    await writeFile(`${path}.content-type`, contentType);
  }

  async get(key: string): Promise<StoredFile> {
    const path = this.pathFor(key);
    try {
      const [body, contentType] = await Promise.all([readFile(path), readFile(`${path}.content-type`, 'utf8')]);
      return { body, contentType };
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
        throw new StoredFileNotFoundError(key);
      }
      throw error;
    }
  }

  /** Keys are API-generated, but never let one point outside the demo folder. */
  private pathFor(key: string): string {
    const path = resolve(join(this.root, key));
    if (!path.startsWith(this.root + sep)) {
      throw new Error('Storage key escapes the demo folder');
    }
    return path;
  }
}

export function createFileStorage(config: AppConfig): FileStorage {
  if (config.storage) {
    const { bucket, ...options } = config.storage;
    return new S3FileStorage(bucket, options);
  }
  new Logger('FileStorage').warn(
    config.isProduction
      ? 'Object storage is not configured: file uploads are refused'
      : 'Object storage is not configured: files are kept in a local temp folder (demo mode)',
  );
  return new DemoFileStorage(config.isProduction);
}
